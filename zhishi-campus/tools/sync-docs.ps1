Get-ChildItem $dir -Filter '*.md' | ForEach-Object {
    $txt = [System.IO.File]::ReadAllText($_.FullName, [System.Text.Encoding]::UTF8)
    $found = [regex]::Matches($txt, '表[34]-\d+[A-D]?') | ForEach-Object { $_.Value } | Sort-Object -Unique
    $bad = $found | Where-Object { $valid -notcontains $_ }
    if ($bad) { "  ⚠ $($_.Name): " + ($bad -join ', ') } else { "  ✓ $($_.Name): " + ($found -join ' ') }
}
